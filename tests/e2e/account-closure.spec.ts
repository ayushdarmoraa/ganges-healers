import crypto from 'node:crypto'
import bcrypt from 'bcryptjs'
import { test, expect } from '@playwright/test'
import { PrismaClient } from '@prisma/client'
import { loadTestDatabaseEnvironment, verifyTestDatabaseConnection } from '../../scripts/test-database'

test('reviewed account closure preserves purchase history, rejects stale confirmation and revokes existing and new sign-ins', async ({ page, browser, baseURL }) => {
  test.setTimeout(150_000)
  const settings = loadTestDatabaseEnvironment()
  await verifyTestDatabaseConnection(settings)
  const db = new PrismaClient({ datasources: { db: { url: settings.environment.DATABASE_URL } } })
  const email = `closure-flow-${crypto.randomUUID()}@example.test`, password = `Owner-${crypto.randomUUID()}!`, stored = await bcrypt.hash(password, 4)
  const user = await db.user.create({ data: { email, password: stored, name: 'Closure owner', freeSessionCredits: 3 } })
  const product = await db.product.create({ data: { slug: `closure-${crypto.randomUUID()}`, title: 'Isolated retained purchase', pricePaise: 1000 } })
  // Billing and fulfillment states below are explicit disposable fixtures, not real charges or fulfillment operations.
  const payment = await db.payment.create({ data: { userId: user.id, type: 'STORE', amountPaise: 1000, gateway: 'razorpay', status: 'success', statusEnum: 'SUCCESS' } })
  const invoice = await db.invoice.create({ data: { paymentId: payment.id, invoiceNumber: crypto.randomUUID(), billTo: {}, lineItems: [], subtotalPaise: 1000, totalPaise: 1000, pdfUrl: 'https://example.test/retained.pdf' } })
  const order = await db.order.create({ data: { userId: user.id, status: 'paid', totalPaise: 1000, paymentId: payment.id, items: { create: { productId: product.id, quantity: 1, pricePaise: 1000 } } } })
  const ledger = await db.sessionCredit.create({ data: { userId: user.id, credits: 2, source: 'isolated-retained-history' } })
  const previousSession = await browser.newContext({ baseURL })
  try {
    expect((await previousSession.request.get('/api/users/account')).status()).toBe(401)
    await page.goto('/auth/signin')
    await page.getByLabel('Email', { exact: true }).fill(email)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Sign In', exact: true }).click()
    await expect(page).toHaveURL(/\/dashboard$/, { timeout: 30_000 })
    await previousSession.addCookies(await page.context().cookies())
    await page.goto('/dashboard/settings')
    const card = page.getByRole('region', { name: 'Close account', exact: true })
    await expect(card.getByRole('link', { name: 'Review orders', exact: true })).toBeVisible({ timeout: 30_000 })
    await expect(card.getByRole('button', { name: 'Close my account', exact: true })).toBeDisabled()
    const reviewResponse = await page.request.get('/api/users/account'), review = await reviewResponse.json()
    expect(reviewResponse.headers()['cache-control']).toBe('private, no-store')
    expect(review).toMatchObject({ ownerId: user.id, reauthenticate: false, blockers: [{ code: 'ORDERS' }] })
    expect(JSON.stringify(review)).not.toContain(stored)
    const wrongOwner = await page.request.delete('/api/users/account', { data: { ownerId: 'another', reviewVersion: review.reviewVersion, acknowledged: true, confirmation: 'CLOSE MY ACCOUNT' } })
    expect(wrongOwner.status()).toBe(409)
    const fulfilled = await db.order.update({ where: { id: order.id }, data: { status: 'fulfilled' }, include: { items: true } })
    await card.getByRole('button', { name: 'Refresh closure review', exact: true }).click()
    await expect(card.getByText('No active commitments currently block closure. The final confirmation checks again.', { exact: true })).toBeVisible()
    await db.user.update({ where: { id: user.id }, data: { name: 'Newer saved owner name' } })
    await card.getByRole('checkbox').check()
    await card.getByLabel('Type CLOSE MY ACCOUNT', { exact: true }).fill('CLOSE MY ACCOUNT')
    await card.getByRole('button', { name: 'Close my account', exact: true }).click()
    await expect(card.getByRole('alert')).toContainText('Your account changed.')
    await expect(card.getByLabel('Type CLOSE MY ACCOUNT', { exact: true })).toHaveValue('CLOSE MY ACCOUNT')
    expect((await db.user.findUniqueOrThrow({ where: { id: user.id } })).closedAt).toBeNull()
    await card.getByRole('button', { name: 'Refresh closure review', exact: true }).click()
    await expect(card.getByLabel('Type CLOSE MY ACCOUNT', { exact: true })).toHaveValue('')
    await expect(card.getByRole('checkbox')).not.toBeChecked()
    const before = await db.user.findUniqueOrThrow({ where: { id: user.id } })
    await card.getByRole('checkbox').check()
    await card.getByLabel('Type CLOSE MY ACCOUNT', { exact: true }).fill('CLOSE MY ACCOUNT')
    await card.getByRole('button', { name: 'Close my account', exact: true }).click()
    await expect(page).toHaveURL(`${baseURL?.replace(/\/$/, '')}/`, { timeout: 30_000 })
    expect((await previousSession.request.get('/api/users/me')).status()).toBe(401)
    const oldSession = await (await previousSession.request.get('/api/auth/session')).json()
    expect(oldSession === null || Object.keys(oldSession).length === 0).toBe(true)
    const after = await db.user.findUniqueOrThrow({ where: { id: user.id } })
    expect(after.closedAt).toBeInstanceOf(Date)
    expect(after).toEqual({ ...before, closedAt: after.closedAt, securityVersion: before.securityVersion + 1, updatedAt: after.updatedAt })
    expect(await db.payment.findUnique({ where: { id: payment.id } })).toEqual(payment)
    expect(await db.invoice.findUnique({ where: { id: invoice.id } })).toEqual(invoice)
    expect(await db.order.findUnique({ where: { id: order.id }, include: { items: true } })).toEqual(fulfilled)
    expect(await db.sessionCredit.findUnique({ where: { id: ledger.id } })).toEqual(ledger)
    expect(await db.activityLog.count({ where: { userId: user.id, action: 'account_closed', entityId: user.id } })).toBe(1)
    await page.goto('/auth/signin')
    await page.getByLabel('Email', { exact: true }).fill(email)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Sign In', exact: true }).click()
    await expect(page.getByRole('form', { name: 'Sign in', exact: true }).getByRole('alert')).toContainText('couldn’t sign you in')
    expect((await page.request.get('/api/users/account')).status()).toBe(401)
  } finally {
    await previousSession.close()
    try { await db.activityLog.deleteMany({ where: { entityId: user.id } }); await db.user.delete({ where: { id: user.id } }); await db.product.delete({ where: { id: product.id } }) }
    finally { await db.$disconnect() }
  }
})
