import React from 'react'
import { act, fireEvent, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import AccountClosureSettings from '@/components/auth/AccountClosureSettings'
import { signOutCurrentSession } from '@/lib/auth/client-session'

const mockReplace = jest.fn(), mockRefresh = jest.fn()
jest.mock('next/navigation', () => ({ useRouter: () => ({ replace: mockReplace, refresh: mockRefresh }) }))
jest.mock('@/lib/auth/client-session', () => ({ signOutCurrentSession: jest.fn() }))
const version = 'a'.repeat(64)
const snapshot = { ownerId: 'owner', reviewVersion: version, reauthenticate: false, expiresAt: new Date(Date.now() + 300_000).toISOString(), blockers: [] }
const receipt = { ownerId: 'owner', closed: true, closedAt: new Date().toISOString() }
const reply = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status })
beforeEach(() => { jest.clearAllMocks(); jest.mocked(signOutCurrentSession).mockResolvedValue(undefined) })
afterEach(() => { jest.restoreAllMocks(); jest.useRealTimers() })
async function confirm() {
  const user = userEvent.setup()
  await user.click(await screen.findByRole('checkbox'))
  await user.type(screen.getByLabelText('Type CLOSE MY ACCOUNT'), 'CLOSE MY ACCOUNT')
  return user
}
test('closure requires explicit retained-record acknowledgement and the exact phrase, then confirms the receipt before sign-out', async () => {
  const fetch = jest.spyOn(globalThis, 'fetch').mockResolvedValueOnce(reply(snapshot)).mockResolvedValueOnce(reply(receipt))
  render(<AccountClosureSettings userId="owner" />)
  expect(await screen.findByRole('button', { name: 'Close my account' })).toBeDisabled()
  const user = await confirm()
  expect(screen.getByRole('button', { name: 'Close my account' })).toBeEnabled()
  await user.click(screen.getByRole('button', { name: 'Close my account' }))
  expect(await screen.findByRole('status')).toHaveTextContent('Your account is closed.')
  expect(fetch).toHaveBeenLastCalledWith('/api/users/account', expect.objectContaining({ method: 'DELETE', body: JSON.stringify({ ownerId: 'owner', reviewVersion: version, confirmation: 'CLOSE MY ACCOUNT', acknowledged: true }) }))
  expect(signOutCurrentSession).toHaveBeenCalledTimes(1)
  expect(mockReplace).toHaveBeenCalledWith('/')
})
test('a stale review failure keeps the confirmation draft and offers explicit refresh', async () => {
  jest.spyOn(globalThis, 'fetch').mockResolvedValueOnce(reply(snapshot)).mockResolvedValueOnce(reply({ error: 'Your account changed. Refresh the review.' }, 409)).mockResolvedValueOnce(reply({ ...snapshot, reviewVersion: 'b'.repeat(64) }))
  render(<AccountClosureSettings userId="owner" />)
  const user = await confirm()
  await user.click(screen.getByRole('button', { name: 'Close my account' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('Your account changed.')
  expect(screen.getByLabelText('Type CLOSE MY ACCOUNT')).toHaveValue('CLOSE MY ACCOUNT')
  expect(screen.getByRole('checkbox')).toBeChecked()
  expect(signOutCurrentSession).not.toHaveBeenCalled()
  await user.click(screen.getByRole('button', { name: 'Refresh closure review' }))
  await screen.findByText('No active commitments currently block closure. The final confirmation checks again.')
  expect(screen.getByLabelText('Type CLOSE MY ACCOUNT')).toHaveValue('')
  expect(screen.getByRole('checkbox')).not.toBeChecked()
})
test.each([{ success: true }, { ...receipt, ownerId: 'another' }, { ...receipt, closed: false }, { ...receipt, closedAt: 'invalid' }])('malformed or other-owner acknowledgements cannot claim closure or sign out (%#)', async body => {
  jest.spyOn(globalThis, 'fetch').mockResolvedValueOnce(reply(snapshot)).mockResolvedValueOnce(reply(body))
  render(<AccountClosureSettings userId="owner" />)
  const user = await confirm()
  await user.click(screen.getByRole('button', { name: 'Close my account' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('could not be confirmed')
  expect(signOutCurrentSession).not.toHaveBeenCalled()
  expect(screen.getByLabelText('Type CLOSE MY ACCOUNT')).toHaveValue('CLOSE MY ACCOUNT')
})
test('missing recent sign-in and active commitments explain the next action and cannot submit', async () => {
  const fetch = jest.spyOn(globalThis, 'fetch').mockResolvedValue(reply({ ...snapshot, reauthenticate: true, expiresAt: null, blockers: [{ code: 'MEMBERSHIPS', message: 'Cancel subscriptions first.' }] }))
  render(<AccountClosureSettings userId="owner" />)
  expect(await screen.findByRole('link', { name: 'Review memberships' })).toHaveAttribute('href', '/dashboard/membership')
  expect(screen.getByRole('link', { name: 'Sign in again' })).toHaveAttribute('href', expect.stringContaining('/auth/signin?callbackUrl='))
  expect(screen.getByRole('button', { name: 'Close my account' })).toBeDisabled()
  fireEvent.submit(screen.getByRole('form', { name: 'Confirm account closure' }))
  expect(fetch).toHaveBeenCalledTimes(1)
})
test('a confirmed closure with failed sign-out offers cleanup without submitting closure twice', async () => {
  jest.spyOn(globalThis, 'fetch').mockResolvedValueOnce(reply(snapshot)).mockResolvedValueOnce(reply(receipt))
  jest.mocked(signOutCurrentSession).mockRejectedValueOnce(new Error('Network unavailable')).mockResolvedValueOnce(undefined)
  render(<AccountClosureSettings userId="owner" />)
  const user = await confirm()
  await user.click(screen.getByRole('button', { name: 'Close my account' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('Your account is closed.')
  await user.click(screen.getByRole('button', { name: 'Finish signing out' }))
  expect(signOutCurrentSession).toHaveBeenCalledTimes(2)
  expect(globalThis.fetch).toHaveBeenCalledTimes(2)
})
test('duplicate submissions are blocked and a later reply from a previous account is ignored', async () => {
  let resolve!: (value: Response) => void
  const fetch = jest.spyOn(globalThis, 'fetch').mockResolvedValueOnce(reply(snapshot)).mockReturnValueOnce(new Promise(done => { resolve = done })).mockResolvedValueOnce(reply({ ...snapshot, ownerId: 'another' }))
  const view = render(<AccountClosureSettings userId="owner" />)
  await confirm()
  const form = screen.getByRole('form', { name: 'Confirm account closure' })
  fireEvent.submit(form); fireEvent.submit(form)
  expect(fetch).toHaveBeenCalledTimes(2)
  view.rerender(<AccountClosureSettings userId="another" />)
  await screen.findByRole('checkbox')
  await act(async () => resolve(reply(receipt)))
  expect(signOutCurrentSession).not.toHaveBeenCalled()
  expect(screen.queryByText('Your account is closed. Sign-in access has ended.')).not.toBeInTheDocument()
  expect(screen.getByLabelText('Type CLOSE MY ACCOUNT')).toHaveValue('')
})
test('review loading errors and mismatched owners offer retry without rendering actionable controls', async () => {
  jest.spyOn(globalThis, 'fetch').mockResolvedValueOnce(reply({ ...snapshot, ownerId: 'another' })).mockResolvedValueOnce(reply(snapshot))
  render(<AccountClosureSettings userId="owner" />)
  expect(await screen.findByRole('alert')).toHaveTextContent('could not be confirmed')
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  await userEvent.click(screen.getByRole('button', { name: 'Refresh closure review' }))
  expect(await screen.findByRole('checkbox')).not.toBeChecked()
})
test('the recent-login timer disables confirmation when the server-issued proof expires', async () => {
  jest.useFakeTimers()
  jest.spyOn(globalThis, 'fetch').mockResolvedValue(reply({ ...snapshot, expiresAt: new Date(Date.now() + 3000).toISOString() }))
  render(<AccountClosureSettings userId="owner" />)
  await act(async () => {})
  fireEvent.click(screen.getByRole('checkbox'))
  fireEvent.change(screen.getByLabelText('Type CLOSE MY ACCOUNT'), { target: { value: 'CLOSE MY ACCOUNT' } })
  expect(screen.getByRole('button', { name: 'Close my account' })).toBeEnabled()
  await act(async () => { jest.advanceTimersByTime(5000) })
  expect(screen.getByRole('button', { name: 'Close my account' })).toBeDisabled()
  expect(screen.getByRole('link', { name: 'Sign in again' })).toBeVisible()
})
